import { useState, useRef, useEffect } from "react";
import { base44 } from "@/api/base44Client";
import { useQuery, useQueryClient } from "@tanstack/react-query";
import { Play, Pause, Volume2, VolumeX, ChevronLeft, ChevronRight, Share2, Download, RefreshCw, AlertCircle } from "lucide-react";
import { Button } from "@/components/ui/button";
import { Card, CardContent } from "@/components/ui/card";
import { toast } from "sonner";

// A "broken" audioUrl is one that has no meaningful file path —
// e.g. stored as just the server origin "https://dev.picard.replit.dev/"
// or as null/empty. These were generated by an older pipeline that lost
// the file path during save. Slides with valid relative paths like
// "/uploads/tts_uuid.wav" are NOT broken.
function isBrokenAudioUrl(url) {
  if (!url) return true;
  try {
    const u = new URL(url, window.location.origin);
    return u.pathname === '/' || u.pathname === '';
  } catch (_) {
    return true;
  }
}

export default function TrainingVideoPlayer() {
  const params = new URLSearchParams(window.location.search);
  const videoId = params.get('id');
  const queryClient = useQueryClient();
  const [currentSlide, setCurrentSlide] = useState(0);
  const [isPlaying, setIsPlaying] = useState(false);
  const [isMuted, setIsMuted] = useState(false);
  const [isFixingAudio, setIsFixingAudio] = useState(false);
  const audioRef = useRef(null);
  // Guards against double-advancing a slide. Broken/slow audio can trigger
  // BOTH the <audio onError> handler AND the play().catch() handler for the
  // same slide, each scheduling its own delayed advance — without this guard
  // both fire and increment currentSlide twice, overshooting slides.length
  // (the "Slide 3 of 2" bug). Reset once per slide in the effect below.
  const advancedRef = useRef(false);

  const { data: video, isLoading } = useQuery({
    queryKey: ['training-video', videoId],
    queryFn: async () => {
      const response = await base44.functions.invoke('getPublicTrainingVideo', { videoId });
      return response.data.video;
    },
    enabled: !!videoId,
  });

  // Single shared advance step — guarded so it can only ever run once per
  // slide, no matter how many of the (up to 4) triggers fire for it.
  const advanceOrStop = () => {
    if (advancedRef.current) return;
    advancedRef.current = true;
    const len = video?.slides?.length || 0;
    if (currentSlide < len - 1) {
      setCurrentSlide(prev => Math.min(prev + 1, len - 1));
    } else {
      setIsPlaying(false);
    }
  };

  const handleAudioEnded = () => {
    advanceOrStop();
  };

  useEffect(() => {
    advancedRef.current = false;
    if (!isPlaying || !video?.slides?.[currentSlide]) return;

    const slide = video.slides[currentSlide];
    const audioUrl = slide.audioUrl;

    // Accept both absolute URLs (https://...) and relative paths (/uploads/...)
    const hasValidAudio = audioUrl && (
      audioUrl.startsWith('http') || audioUrl.startsWith('/')
    ) && !isBrokenAudioUrl(audioUrl);

    if (hasValidAudio && audioRef.current) {
      // Reset audio element first
      audioRef.current.pause();
      audioRef.current.currentTime = 0;
      audioRef.current.src = audioUrl;
      audioRef.current.muted = isMuted;

      // Play with a small delay to ensure source is loaded
      const playTimer = setTimeout(() => {
        audioRef.current?.play().catch(err => {
          console.error('Audio playback failed:', err);
          // Audio failed to play — fall back to a timed advance so we
          // don't cascade through every slide in milliseconds. Guarded by
          // advancedRef in case <audio onError> already advanced us.
          setTimeout(advanceOrStop, 3000);
        });
      }, 50);

      return () => clearTimeout(playTimer);
    } else {
      // No audio or broken URL — advance after 3 seconds
      const timer = setTimeout(advanceOrStop, 3000);
      return () => clearTimeout(timer);
    }
  }, [isPlaying, currentSlide, video, isMuted]);

  const togglePlayPause = () => {
    if (isPlaying) {
      audioRef.current?.pause();
      setIsPlaying(false);
    } else {
      // Stop and reset any current audio
      if (audioRef.current) {
        audioRef.current.pause();
        audioRef.current.currentTime = 0;
        audioRef.current.src = '';
      }

      // Force reset to first slide
      setCurrentSlide(0);
      setIsPlaying(false); // Ensure it's stopped first

      // Start playing after a brief delay to ensure state is updated
      requestAnimationFrame(() => {
        setIsPlaying(true);
      });
    }
  };

  const handleFixAudio = async () => {
    if (!videoId || isFixingAudio) return;
    setIsFixingAudio(true);
    toast.loading('Regenerating audio for all slides… this takes about 10–30 seconds.', { id: 'fix-audio', duration: 60000 });
    try {
      const result = await base44.functions.invoke('refreshTrainingVideoAudio', {
        videoId,
        voice: 'Kore',
      });
      const { regenerated, failed, total } = result?.data || {};
      if (result?.data?.error) throw new Error(result.data.error);
      toast.success(
        `Audio fixed! ${regenerated} of ${total} slides now have audio.${failed ? ` ${failed} failed — try again.` : ''}`,
        { id: 'fix-audio', duration: 6000 }
      );
      // Reload the video data so the player picks up the new audioUrls
      queryClient.invalidateQueries({ queryKey: ['training-video', videoId] });
    } catch (err) {
      toast.error('Audio fix failed: ' + err.message, { id: 'fix-audio' });
    } finally {
      setIsFixingAudio(false);
    }
  };

  if (isLoading) {
    return (
      <div className="min-h-screen flex items-center justify-center bg-gray-900">
        <div className="text-white text-xl">Loading training video...</div>
      </div>
    );
  }

  if (!video) {
    return (
      <div className="min-h-screen flex items-center justify-center bg-gray-900">
        <div className="text-white text-xl">Training video not found</div>
      </div>
    );
  }

  const slides = video.slides || [];
  const currentSlideData = slides[currentSlide];

  // Check if any slide has a broken audioUrl (so we can show the fix banner)
  const slidesWithNarration = slides.filter(s => s.narration?.trim());
  const brokenCount = slidesWithNarration.filter(s => isBrokenAudioUrl(s.audioUrl)).length;
  const hasAudioProblem = brokenCount > 0;

  return (
    <div className="min-h-screen bg-gray-900 flex flex-col">
      {/* Header */}
      <div className="bg-gray-800 border-b border-gray-700 px-6 py-4">
        <h1 className="text-2xl font-bold text-white">{video.title}</h1>
        {video.description && (
          <p className="text-gray-400 mt-1">{video.description}</p>
        )}
      </div>

      {/* Audio-broken banner */}
      {hasAudioProblem && (
        <div className="bg-amber-900/60 border-b border-amber-700 px-6 py-3 flex items-center justify-between gap-4">
          <div className="flex items-center gap-2 text-amber-200">
            <AlertCircle className="w-4 h-4 flex-shrink-0" />
            <span className="text-sm">
              Audio is missing for {brokenCount} of {slidesWithNarration.length} narrated slides
              (stored on a previous server). Click "Fix Audio" to regenerate.
            </span>
          </div>
          <Button
            size="sm"
            onClick={handleFixAudio}
            disabled={isFixingAudio}
            className="bg-amber-600 hover:bg-amber-700 text-white flex-shrink-0"
          >
            {isFixingAudio ? (
              <><RefreshCw className="w-4 h-4 mr-2 animate-spin" />Fixing…</>
            ) : (
              <><RefreshCw className="w-4 h-4 mr-2" />Fix Audio</>
            )}
          </Button>
        </div>
      )}

      {/* Main Content */}
      <div className="flex-1 flex items-center justify-center p-6">
        <div className="w-full max-w-6xl">
          <Card className="bg-black border-2 border-gray-700">
            <CardContent className="p-0">
              {/* Video Display */}
              <div className="relative aspect-video bg-black">
                {currentSlideData?.imageUrl && (
                  <img
                    src={currentSlideData.imageUrl}
                    alt={`Slide ${currentSlide + 1}`}
                    className="w-full h-full object-contain"
                  />
                )}

                {/* Caption Overlay */}
                {currentSlideData?.caption && (
                  <div className="absolute bottom-0 left-0 right-0 bg-black bg-opacity-75 text-white p-4 text-center">
                    <p className="text-lg">{currentSlideData.caption}</p>
                  </div>
                )}

                {/* Play/Pause Overlay */}
                {!isPlaying && (
                  <div className="absolute inset-0 flex items-center justify-center">
                    <Button
                      size="lg"
                      onClick={togglePlayPause}
                      className="bg-blue-600 hover:bg-blue-700 w-20 h-20 rounded-full"
                    >
                      <Play className="w-10 h-10" />
                    </Button>
                  </div>
                )}
              </div>

              {/* Controls */}
              <div className="bg-gray-800 p-4">
                <div className="flex items-center justify-between mb-3">
                  <Button
                    variant="ghost"
                    size="sm"
                    onClick={() => setCurrentSlide(Math.max(0, currentSlide - 1))}
                    disabled={currentSlide === 0 || isPlaying}
                    className="text-white hover:bg-gray-700"
                  >
                    <ChevronLeft className="w-5 h-5 mr-1" />
                    Previous
                  </Button>

                  <div className="text-white text-sm font-medium">
                    Slide {currentSlide + 1} of {slides.length}
                  </div>

                  <Button
                    variant="ghost"
                    size="sm"
                    onClick={() => setCurrentSlide(Math.min(slides.length - 1, currentSlide + 1))}
                    disabled={currentSlide === slides.length - 1 || isPlaying}
                    className="text-white hover:bg-gray-700"
                  >
                    Next
                    <ChevronRight className="w-5 h-5 ml-1" />
                  </Button>
                </div>

                <div className="flex items-center justify-center gap-4">
                  <Button
                    onClick={togglePlayPause}
                    className="bg-blue-600 hover:bg-blue-700"
                  >
                    {isPlaying ? (
                      <>
                        <Pause className="w-4 h-4 mr-2" />
                        Pause
                      </>
                    ) : (
                      <>
                        <Play className="w-4 h-4 mr-2" />
                        Start Training
                      </>
                    )}
                  </Button>

                  <Button
                    variant="ghost"
                    size="icon"
                    onClick={() => setIsMuted(!isMuted)}
                    className="text-white hover:bg-gray-700"
                  >
                    {isMuted ? <VolumeX className="w-5 h-5" /> : <Volume2 className="w-5 h-5" />}
                  </Button>

                  <Button
                    variant="ghost"
                    size="icon"
                    onClick={() => {
                      const shareUrl = window.location.href;
                      navigator.clipboard.writeText(shareUrl);
                      toast.success('Share link copied to clipboard!');
                    }}
                    className="text-white hover:bg-gray-700"
                    title="Share this training video"
                  >
                    <Share2 className="w-5 h-5" />
                  </Button>

                  <Button
                    variant="ghost"
                    size="icon"
                    onClick={() => {
                      if (video.video_url) {
                        const link = document.createElement('a');
                        link.href = video.video_url;
                        link.download = `${video.title || 'training-video'}.mp4`;
                        document.body.appendChild(link);
                        link.click();
                        document.body.removeChild(link);
                        toast.success('Downloading video...');
                      } else {
                        toast.error('Video file not available. Generate the video first in the builder.');
                      }
                    }}
                    className="text-white hover:bg-gray-700"
                    title="Download training video"
                  >
                    <Download className="w-5 h-5" />
                  </Button>
                </div>

                {/* Progress Bar */}
                <div className="mt-4 bg-gray-700 h-2 rounded-full overflow-hidden">
                  <div
                    className="bg-blue-600 h-full transition-all duration-300"
                    style={{ width: `${((currentSlide + 1) / slides.length) * 100}%` }}
                  />
                </div>
              </div>
            </CardContent>
          </Card>
        </div>
      </div>

      {/* Hidden audio player */}
      {/* No crossOrigin="anonymous" — object-storage audio URLs may not send
          CORS headers; adding that attribute forces a CORS preflight that fails
          and triggers onError, which used to cascade all slides to the end. */}
      <audio
        ref={audioRef}
        onEnded={handleAudioEnded}
        onError={(e) => {
          console.error('Audio load error:', e);
          // Audio failed to load — wait 3 s (same as no-audio path) before
          // advancing so slides don't cascade to the end immediately.
          // Guarded by advancedRef in case play().catch() already advanced us.
          setTimeout(advanceOrStop, 3000);
        }}
        className="hidden"
      />
    </div>
  );
}
